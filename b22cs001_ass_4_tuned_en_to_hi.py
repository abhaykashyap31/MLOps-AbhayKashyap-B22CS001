def translate_sentence(model, sentence, en_vocab, hi_vocab, *, src_pad_idx: int, tgt_pad_idx: int, device: torch.device, max_len=50):
    model.eval()
    tokens = encode_sentence(sentence, en_vocab, max_len=max_len)
    src_tensor = torch.tensor(tokens).unsqueeze(0).to(device)

    tgt_tokens = [hi_vocab["<sos>"]]
    for _ in range(max_len):
        tgt_tensor = torch.tensor(tgt_tokens).unsqueeze(0).to(device)
        with torch.no_grad():
            output = model(src_tensor, tgt_tensor, src_pad_idx, tgt_pad_idx)
        next_token = output[0, -1].argmax().item()
        tgt_tokens.append(next_token)
        if next_token == hi_vocab["<eos>"]:
            break

    translated = [hi_vocab.itos[idx] for idx in tgt_tokens[1:-1]]
    return ' '.join(translated)

import nltk
from nltk.translate.bleu_score import sentence_bleu, corpus_bleu, SmoothingFunction

smoothie = SmoothingFunction().method4

def evaluate_bleu_nltk(model, dataset, en_vocab, hi_vocab, max_len=50):
    references = []
    hypotheses = []

    for en_sentence, hi_sentence in dataset:
        pred = translate_sentence(
            model,
            en_sentence,
            en_vocab,
            hi_vocab,
            src_pad_idx=en_vocab["<pad>"],
            tgt_pad_idx=hi_vocab["<pad>"],
            device=DEVICE,
            max_len=max_len,
        )
        pred_tokens = pred.split()
        ref_tokens = hi_sentence.split()

        references.append([ref_tokens])   # list of reference lists
        hypotheses.append(pred_tokens)    # list of predicted tokens

    score = corpus_bleu(references, hypotheses, smoothing_function=smoothie)
    print(f"🌐 BLEU Score (NLTK): {score * 100:.2f}")
    return score


def run_tune(
    *,
    num_samples: int = 20,
    trial_max_epochs: int = 15,
) -> None:
    """
    Ray Tune + Optuna search with ASHA early stopping.
    Each trial is capped at <= trial_max_epochs epochs (ASHA may stop earlier).
    """
    import ray
    from ray import tune
    from ray import air
    from ray.tune.schedulers import ASHAScheduler
    from ray.tune.search.optuna import OptunaSearch

    # Explicitly initialize Ray with at least 1 CPU to ensure proper resource management
    ray.init(num_cpus=1, num_gpus=1, ignore_reinit_error=True)

    param_space = {
        # Trial cap (Part 3 requirement).
        "max_epochs": trial_max_epochs,
        "data_path": "/content/English-Hindi.tsv", # Updated to absolute path
        "freq_threshold": 2,
        "max_len": 50,
        "d_model": 512,  # keep constant so num_heads choices stay valid

        # Vary >=4 impactful hyperparameters (Part 2.2).
        "lr": tune.loguniform(1e-5, 1e-3),
        "batch_size": tune.choice([16, 32, 64]),
        "num_heads": tune.choice([4, 8]),
        "d_ff": tune.choice([1024, 2048]),
        "dropout": tune.uniform(0.1, 0.4),
    }

    optuna_search = OptunaSearch(metric="loss", mode="min")
    asha = ASHAScheduler(
        metric="loss",
        mode="min",
        max_t=trial_max_epochs,
        grace_period=max(1, min(3, trial_max_epochs // 5)),
        reduction_factor=2,
    )

    tuner = tune.Tuner(
        tune.with_resources(train_tune, resources={"cpu": 1, "gpu": 1}), # Request 1 CPU and 1 GPU for each trial
        tune_config=tune.TuneConfig(
            search_alg=optuna_search,
            scheduler=asha,
            num_samples=num_samples,
        ),
        param_space=param_space,
        run_config=air.RunConfig(name="tune_run")
    )

    results = tuner.fit()
    best = results.get_best_result(metric="loss", mode="min")
    print("\nBest trial:")
    print(best.metrics)
    print(best.config)


