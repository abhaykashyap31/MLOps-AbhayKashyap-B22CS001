DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
def build_transformer_from_config(
    config: dict,
    *,
    src_vocab_size: int,
    tgt_vocab_size: int,
    max_len: int,
    device: torch.device,
) -> nn.Module:
    d_model = int(config.get("d_model", 512))
    num_heads = int(config.get("num_heads", 8))
    if d_model % num_heads != 0:
        raise ValueError(f"d_model ({d_model}) must be divisible by num_heads ({num_heads}).")

    model = Transformer(
        src_vocab_size=src_vocab_size,
        tgt_vocab_size=tgt_vocab_size,
        d_model=d_model,
        num_layers=int(config.get("num_layers", 6)),
        num_heads=num_heads,
        d_ff=int(config.get("d_ff", 2048)),
        max_len=max_len,
        dropout=float(config.get("dropout", 0.1)),
    ).to(device)
    return model

import os

def save_checkpoint(epoch, model, optimizer, loss, path="checkpoint.pt"):
    torch.save({
        'epoch': epoch,
        'model_state': model.state_dict(),
        'optimizer_state': optimizer.state_dict(),
        'loss': loss
    }, path)

    print(f"Checkpoint saved at epoch {epoch}, loss {loss:.4f}.")

def load_checkpoint(model, optimizer, path="checkpoint.pt"):
    if torch.cuda.is_available() and path is not None and os.path.exists(path):
        checkpoint = torch.load(path)
    elif path is not None and os.path.exists(path):
        checkpoint = torch.load(path, map_location=torch.device('cpu'))
    else:
        print(f"No checkpoint found at {path}. Starting from scratch.")
        return 0

    model.load_state_dict(checkpoint['model_state'])
    optimizer.load_state_dict(checkpoint['optimizer_state'])

    epoch = checkpoint['epoch']
    loss = checkpoint['loss']

    print(f"✅ Loaded checkpoint from epoch {epoch} with loss {loss:.4f}")

    return epoch

def train(
    model,
    train_loader,
    optimizer,
    criterion,
    *,
    src_pad_idx: int,
    tgt_pad_idx: int,
    device: torch.device,
    start_epoch: int = 0,
    num_epochs: int = 100,
    checkpoint_path: str = "checkpoint.pt",
):
    for epoch in range(start_epoch, num_epochs):
        model.train()
        epoch_loss = 0
        loop = tqdm(train_loader, desc=f"Epoch [{epoch+1}/{num_epochs}]")

        for src, tgt_input, tgt_output in loop:
            src = src.to(device)
            tgt_input = tgt_input.to(device)
            tgt_output = tgt_output.to(device)

            output = model(src, tgt_input, src_pad_idx, tgt_pad_idx)
            output = output.reshape(-1, output.shape[-1]) # Changed .view to .reshape
            tgt_output = tgt_output.reshape(-1) # Changed .view to .reshape

            loss = criterion(output, tgt_output)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            epoch_loss += loss.item()
            loop.set_postfix(loss=loss.item())

        # Save checkpoint at end of each epoch
        save_checkpoint(epoch+1, model, optimizer, epoch_loss / len(train_loader), checkpoint_path)

